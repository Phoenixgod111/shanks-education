import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const readJson = async (relative) => JSON.parse(await readFile(path.join(root, relative), "utf8"));

const manifest = await readJson("content/manifest.json");
const trajectories = {};
const trajectoryFiles = (await readdir(path.join(root, "curriculum", "trajectories")))
  .filter((file) => file.endsWith(".json"))
  .sort();
for (const file of trajectoryFiles) {
  const trajectory = await readJson(`curriculum/trajectories/${file}`);
  trajectories[trajectory.catalogId] = trajectory;
}

const contentByTopicId = {};
for (const grade of Object.keys(manifest.grades).sort((a, b) => Number(a) - Number(b))) {
  const collection = await readJson(manifest.grades[grade]);
  for (const packet of collection.packets) contentByTopicId[packet.topicId] = packet;
}

const payload = {
  canonical: await readJson("curriculum/canonical/topics.json"),
  catalog: await readJson("curriculum/catalog/textbook-lines.json"),
  trajectories,
  contentByTopicId,
  contentManifest: manifest,
  rights: await readJson("content/rights/registry.json")
};
const target = path.join(root, "js", "math-content-data-embed.js");
const body = `// Generated by scripts/generate-content-embed.mjs. Do not edit by hand.\nwindow.SHANKS_MATH_CONTENT_DATA=${JSON.stringify(payload)};\n`;
await writeFile(target, body, "utf8");
console.log(`generated ${path.relative(root, target)} with ${Object.keys(contentByTopicId).length} packets`);
